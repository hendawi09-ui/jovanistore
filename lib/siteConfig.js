export const governorates = shipping.zones
  .flatMap((z) => z.govs)
  .sort((a, b) => a.localeCompare(b, "ar"));

// بيرجع سعر الشحن للمحافظة المختارة (null لو مفيش محافظة متحددة)
export function shippingFor(gov) {
  if (!gov) return null;
  const zone = shipping.zones.find((z) => z.govs.includes(gov));
  return zone ? zone.price : null;
}

